# 生成戰鬥用圖：敵人 32x32 x5（黃巾兵、弓手、山賊、小帥、程遠志）。python3 tools/build_battle_assets.py
from PIL import Image, ImageDraw
import os
OUT = os.path.join(os.path.dirname(__file__), '..', 'assets')
S = 32
img = Image.new('RGBA', (S * 5, S), (0, 0, 0, 0))
d = ImageDraw.Draw(img)
OL = (24, 16, 24, 255)

def R(ox, x0, y0, x1, y1, c): d.rectangle([ox + x0, y0, ox + x1, y1], fill=c)

def person(i, skin, cloth, cloth2, head, weapon=None, big=False, hat=None):
    ox = i * S
    # 腿
    R(ox, 11, 24, 14, 30, cloth2); R(ox, 17, 24, 20, 30, cloth2)
    R(ox, 10, 30, 14, 31, OL); R(ox, 17, 30, 21, 31, OL)
    # 身體
    R(ox, 9, 13, 22, 24, OL); R(ox, 10, 14, 21, 23, cloth)
    R(ox, 10, 19, 21, 20, cloth2)
    # 手臂
    R(ox, 6, 14, 9, 21, OL); R(ox, 7, 15, 8, 20, skin)
    R(ox, 22, 14, 25, 21, OL); R(ox, 23, 15, 24, 20, skin)
    # 頭
    R(ox, 10, 3, 21, 13, OL); R(ox, 11, 4, 20, 12, skin)
    R(ox, 13, 8, 14, 9, OL); R(ox, 17, 8, 18, 9, OL)
    R(ox, 14, 11, 17, 11, (150, 70, 60, 255))
    # 頭巾／帽
    R(ox, 10, 3, 21, 6, OL); R(ox, 11, 4, 20, 5, head)
    if hat == 'turban':
        R(ox, 9, 6, 22, 7, head); R(ox, 8, 7, 9, 10, head)
    return ox

YEL = (232, 196, 48, 255); YEL2 = (180, 140, 30, 255)
SK = (240, 200, 160, 255)
# 0 黃巾兵：黃頭巾、褐衣、長矛
ox = person(0, SK, (150, 110, 70, 255), (100, 70, 45, 255), YEL, None, hat='turban')
R(ox, 26, 4, 26, 28, (120, 90, 60, 255)); R(ox, 25, 2, 27, 5, (200, 200, 220, 255))
# 1 弓手：黃頭巾、綠衣、弓
ox = person(1, SK, (90, 130, 80, 255), (60, 90, 55, 255), YEL, None, hat='turban')
for k in range(0, 18):
    x = 5 - int(((k - 9) ** 2) / 12.0)
    d.point([ox + 26 + (-x + 5), 8 + k], fill=(160, 110, 60, 255))
d.line([ox + 26, 8, ox + 26, 25], fill=(230, 230, 230, 255))
# 2 山賊：紅巾、深色皮甲、大刀
ox = person(2, (220, 170, 130, 255), (70, 70, 90, 255), (45, 45, 60, 255), (190, 50, 50, 255))
R(ox, 25, 6, 26, 24, (200, 200, 220, 255)); R(ox, 24, 24, 27, 27, (110, 70, 40, 255))
R(ox, 11, 10, 20, 12, (60, 40, 30, 255))   # 鬍
# 3 黃巾小帥：黃盔、橘甲、盾
ox = person(3, SK, (210, 120, 40, 255), (150, 80, 30, 255), YEL)
R(ox, 9, 2, 22, 3, YEL2); R(ox, 15, 0, 16, 3, (200, 60, 50, 255))
R(ox, 2, 14, 8, 24, OL); R(ox, 3, 15, 7, 23, (230, 200, 60, 255)); R(ox, 4, 18, 6, 20, (180, 60, 40, 255))
R(ox, 25, 8, 26, 26, (200, 200, 220, 255))
# 4 程遠志：大型、黃金甲、雙刀、大鬍
ox = 4 * S
R(ox, 9, 23, 14, 30, (120, 90, 30, 255)); R(ox, 17, 23, 22, 30, (120, 90, 30, 255))
R(ox, 8, 30, 14, 31, OL); R(ox, 17, 30, 23, 31, OL)
R(ox, 5, 11, 26, 24, OL); R(ox, 6, 12, 25, 23, (235, 190, 50, 255)); R(ox, 6, 17, 25, 18, (170, 120, 30, 255))
R(ox, 13, 13, 18, 16, (200, 60, 50, 255))
R(ox, 2, 12, 5, 20, OL); R(ox, 3, 13, 4, 19, SK); R(ox, 26, 12, 29, 20, OL); R(ox, 27, 13, 28, 19, SK)
R(ox, 9, 1, 22, 12, OL); R(ox, 10, 3, 21, 11, SK)
R(ox, 9, 0, 22, 4, OL); R(ox, 10, 1, 21, 3, (235, 190, 50, 255)); R(ox, 14, 0, 17, 1, (200, 60, 50, 255))
R(ox, 12, 6, 14, 7, OL); R(ox, 17, 6, 19, 7, OL)
R(ox, 11, 9, 20, 12, (40, 30, 30, 255))
R(ox, 0, 2, 1, 22, (210, 210, 230, 255)); R(ox, 30, 2, 31, 22, (210, 210, 230, 255))
img.save(os.path.join(OUT, 'enemies.png'))
